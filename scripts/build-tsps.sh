#!/usr/bin/env bash
# Build Apotris for Trimui Smart Pro S (Allwinner A133P, aarch64).
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="$ROOT_DIR/build-spruce-aarch64"
CACHE_DIR="$ROOT_DIR/.tsps-build"
SYSROOT="$CACHE_DIR/sysroot"
VENV_DIR="$CACHE_DIR/tools/venv"
STUB_DIR="$CACHE_DIR/link-stubs"
CXX_OVERLAY_DIR="$CACHE_DIR/gcc10-cxx-headers"
LOCAL_CROSS_FILE="$ROOT_DIR/meson/spruce-aarch64.local.ini"
LOCAL_CROSS_SUM="$CACHE_DIR/spruce-aarch64.local.ini.cksum"
READY_FILE="$CACHE_DIR/toolchain-aarch64.ready"
JOBS="${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || printf '4')}"
C_COMPILER='aarch64-linux-gnu-gcc-10'
CXX_COMPILER='aarch64-linux-gnu-g++-10'
GCC_INCLUDE_DIR='/usr/lib/gcc-cross/aarch64-linux-gnu/10/include'

require_command() {
    command -v "$1" >/dev/null 2>&1 || {
        printf 'Missing prerequisite: %s\n' "$1" >&2
        exit 1
    }
}

for command in "$C_COMPILER" "$CXX_COMPILER" ninja readelf; do
    require_command "$command"
done
for path in "$READY_FILE" "$VENV_DIR/bin/meson" \
    "$SYSROOT/lib/aarch64-linux-gnu/libc-2.28.so" \
    "$SYSROOT/usr/lib/aarch64-linux-gnu/libstdc++.so.6" \
    "$SYSROOT/lib/aarch64-linux-gnu/libgcc_s.so.1" \
    "$SYSROOT/usr/lib/aarch64-linux-gnu/libpthread.so" \
    "$CXX_OVERLAY_DIR/cstddef" "$STUB_DIR/libGLESv2.so"; do
    [[ -e "$path" ]] || {
        printf 'Toolchain not ready: %s\nRun ./scripts/setup-toolchain.sh first.\n' "$path" >&2
        exit 1
    }
done
[[ -f "$ROOT_DIR/subprojects/Tilengine/meson.build" ]] || {
    printf '%s\n' 'Submodules are incomplete. Run: git submodule update --init --recursive' >&2
    exit 1
}

MESON="$VENV_DIR/bin/meson"
printf '%s\n' '# Generated by scripts/build-tsps.sh; do not commit.' > "$LOCAL_CROSS_FILE"
printf '%s\n' '' '[properties]' 'needs_exe_wrapper = true' \
    "spruce_glesv2 = '$STUB_DIR/libGLESv2.so'" \
    'spruce_no_openssl = true' '' '[built-in options]' \
    "c_args = ['--sysroot=$SYSROOT', '-B$SYSROOT/usr/lib/aarch64-linux-gnu', '-nostdinc', '-isystem', '$SYSROOT/usr/include/aarch64-linux-gnu', '-isystem', '$SYSROOT/usr/include', '-idirafter', '$GCC_INCLUDE_DIR', '-march=armv8-a']" \
    "cpp_args = ['--sysroot=$SYSROOT', '-B$SYSROOT/usr/lib/aarch64-linux-gnu', '-nostdinc', '-nostdinc++', '-isystem', '$CXX_OVERLAY_DIR', '-isystem', '$CXX_OVERLAY_DIR/aarch64-linux-gnu', '-isystem', '$CXX_OVERLAY_DIR/backward', '-isystem', '$SYSROOT/usr/include/aarch64-linux-gnu', '-isystem', '$SYSROOT/usr/include', '-idirafter', '$GCC_INCLUDE_DIR', '-march=armv8-a']" \
    "c_link_args = ['--sysroot=$SYSROOT', '-B$SYSROOT/usr/lib/aarch64-linux-gnu', '-march=armv8-a']" \
    "cpp_link_args = ['--sysroot=$SYSROOT', '-B$SYSROOT/usr/lib/aarch64-linux-gnu', '-march=armv8-a', '-nodefaultlibs', '$SYSROOT/usr/lib/aarch64-linux-gnu/libstdc++.so.6', '-lm', '$SYSROOT/lib/aarch64-linux-gnu/libgcc_s.so.1', '-lc', '$SYSROOT/usr/lib/aarch64-linux-gnu/libpthread.so', '-lgcc']" \
    >> "$LOCAL_CROSS_FILE"

current_cross_sum="$(cksum "$ROOT_DIR/meson/spruce-aarch64.ini" "$LOCAL_CROSS_FILE")"
previous_cross_sum="$(test -f "$LOCAL_CROSS_SUM" && < "$LOCAL_CROSS_SUM" || true)"
if [[ -d "$BUILD_DIR" && "$current_cross_sum" == "$previous_cross_sum" ]]; then
    "$MESON" setup --reconfigure "$BUILD_DIR" \
        --cross-file "$ROOT_DIR/meson/spruce-aarch64.ini" \
        --cross-file "$LOCAL_CROSS_FILE" --force-fallback-for=zlib \
        -Dportmaster=true --buildtype=release
elif [[ -d "$BUILD_DIR" ]]; then
    "$MESON" setup --wipe "$BUILD_DIR" \
        --cross-file "$ROOT_DIR/meson/spruce-aarch64.ini" \
        --cross-file "$LOCAL_CROSS_FILE" --force-fallback-for=zlib \
        -Dportmaster=true --buildtype=release
else
    "$MESON" setup "$BUILD_DIR" \
        --cross-file "$ROOT_DIR/meson/spruce-aarch64.ini" \
        --cross-file "$LOCAL_CROSS_FILE" --force-fallback-for=zlib \
        -Dportmaster=true --buildtype=release
fi

# Check Meson's generated graph rather than trusting its cached cross-file.
if ! ninja -C "$BUILD_DIR" -t commands | grep -F -- "-idirafter $GCC_INCLUDE_DIR" >/dev/null; then
    printf '%s\n' 'Refreshing stale Meson cross-build commands...'
    "$MESON" setup --wipe "$BUILD_DIR" \
        --cross-file "$ROOT_DIR/meson/spruce-aarch64.ini" \
        --cross-file "$LOCAL_CROSS_FILE" --force-fallback-for=zlib \
        -Dportmaster=true --buildtype=release
fi
printf '%s\n' "$current_cross_sum" > "$LOCAL_CROSS_SUM"

ninja -C "$BUILD_DIR" -j"$JOBS"

require_at_most() {
    local namespace="$1" maximum="$2" version
    shift 2
    for version in "$@"; do
        if [[ "$(printf '%s\n%s\n' "$maximum" "$version" | sort -V | tail -n1)" != "$maximum" ]]; then
            printf '%s %s exceeds the console maximum %s\n' "$namespace" "$version" "$maximum" >&2
            exit 1
        fi
    done
}

readelf -h "$BUILD_DIR/Apotris" | grep -q 'Machine:.*AArch64' || {
    printf 'Build artifact is not AArch64: %s\n' "$BUILD_DIR/Apotris" >&2
    exit 1
}
mapfile -t glibc_versions < <(readelf --version-info "$BUILD_DIR/Apotris" | grep -oE 'GLIBC_[0-9]+\.[0-9]+' | sed 's/GLIBC_//' | sort -Vu)
mapfile -t glibcxx_versions < <(readelf --version-info "$BUILD_DIR/Apotris" | grep -oE 'GLIBCXX_[0-9]+\.[0-9]+(\.[0-9]+)?' | sed 's/GLIBCXX_//' | sort -Vu)
mapfile -t cxxabi_versions < <(readelf --version-info "$BUILD_DIR/Apotris" | grep -oE 'CXXABI_[0-9]+(\.[0-9]+)+' | sed 's/CXXABI_//' | sort -Vu)
require_at_most GLIBC 2.33 "${glibc_versions[@]}"
require_at_most GLIBCXX 3.4.28 "${glibcxx_versions[@]}"
require_at_most CXXABI 1.3.13 "${cxxabi_versions[@]}"

printf '\nBuild complete: %s\n' "$BUILD_DIR/Apotris"
printf '%s\n' 'This is a build artifact, not yet the final PortMaster package.'
